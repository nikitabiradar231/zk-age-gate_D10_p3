import * as fs from "fs";
import * as path from "path";
import { createAgeCredential } from "../src/client/credential";
import { generateAgeProof } from "../src/client/prove";
import {
  DEFAULT_TEST_REF_DAY,
  DEFAULT_TEST_REF_MONTH,
  DEFAULT_TEST_REF_YEAR,
} from "../src/shared/constants";

/**
 * CLI script to generate a real Barretenberg UltraHonk proof locally.
 * Demonstrates an eligible buyer claiming an age-gated festival pass.
 */
async function main() {
  console.log("=== zk-age-gate: Buyer Local Proof Generation ===");

  // Default synthetic eligible buyer: born May 15, 2005 (Age 21 on reference date 2026-10-23)
  const claimantAddress = process.argv[2] || "0x70997970C51812dc3A010C7d01b50e0d17dc79C8";
  const birthYear = parseInt(process.argv[3] || "2005", 10);
  const birthMonth = parseInt(process.argv[4] || "5", 10);
  const birthDay = parseInt(process.argv[5] || "15", 10);

  console.log(`1. Door partner off-chain verification simulated...`);
  console.log(`   Claimant account: ${claimantAddress}`);
  console.log(`   Birth date verified by door partner: [CONFIDENTIAL - kept strictly local]`);

  const credential = createAgeCredential({
    birthDate: { year: birthYear, month: birthMonth, day: birthDay },
  });

  const refDate = {
    year: DEFAULT_TEST_REF_YEAR,
    month: DEFAULT_TEST_REF_MONTH,
    day: DEFAULT_TEST_REF_DAY,
  };
  const claimTimestamp = Math.floor(Date.now() / 1000);

  console.log(`2. Generating local witness and UltraHonk proof with Barretenberg...`);
  const proofOutput = await generateAgeProof(
    credential,
    {
      claimantAddress,
      referenceDate: refDate,
      claimTimestamp,
    },
    { verifyLocally: true, verbose: false }
  );

  console.log(`3. Proof generated and verified locally!`);
  console.log(`   Proof length: ${(proofOutput.proofHex.length - 2) / 2} bytes`);
  console.log(`   Public inputs count: ${proofOutput.publicInputs.length}`);
  console.log(`   Nullifier: ${proofOutput.nullifierHex}`);

  // Save to test fixtures directory for Foundry / integration testing
  const fixturesDir = path.resolve(__dirname, "..", "test", "fixtures");
  fs.mkdirSync(fixturesDir, { recursive: true });

  const fixturePath = path.join(fixturesDir, "proof_fixture.json");
  fs.writeFileSync(
    fixturePath,
    JSON.stringify(
      {
        proofHex: proofOutput.proofHex,
        publicInputs: proofOutput.publicInputs,
        nullifierHex: proofOutput.nullifierHex,
        claimant: proofOutput.claimant,
        claimTimestamp: proofOutput.claimTimestamp,
        referenceDate: proofOutput.referenceDate,
        description: "Synthetic valid adult proof generated by Barretenberg UltraHonk",
      },
      null,
      2
    ),
    "utf-8"
  );

  console.log(`✓ Proof fixture saved to: ${path.relative(process.cwd(), fixturePath)}`);
  console.log(`\nReady to submit claim to AgeGate.sol on-chain.`);
}

main().catch((err) => {
  console.error("Proof generation failed:", err.message);
  process.exit(1);
});
